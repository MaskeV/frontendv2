  freeableMemoryChart: Highcharts.Chart | null = null;
  rdsSwapUsageChart: Highcharts.Chart | null = null;
  databaseConnectionsCharts: Highcharts.Chart | null = null;
  freeStorageSpaceChart: Highcharts.Chart | null = null;
  diskQueueDepthChart: Highcharts.Chart | null = null;
  readLatencyChart: Highcharts.Chart | null = null;
  readIopsChart: Highcharts.Chart | null = null;
  writeIopsChart: Highcharts.Chart | null = null;
  readThroughputChart: Highcharts.Chart | null = null;
  writeThroughputChart: Highcharts.Chart | null = null;
  networkReceiveThroughputChart: Highcharts.Chart | null = null;
  networkTransmitThroughputChart: Highcharts.Chart | null = null;

  constructor(
    private dateService: DateService,
    private rdsApiService: RdsApiService,
  ) { }

  ngOnInit(): void {
    this.selectedService = sessionStorage.getItem('serviceIdForRds')!;
    this.serviceId = sessionStorage.getItem('encodedServiceIdForRds')!;
    this.dateService.setActiveComponent('RdsServiceComponent');
    this.datesubscription = this.dateService.activeComponent$.pipe(
      filter(activeComponent => activeComponent === 'RdsServiceComponent'),
      switchMap(() => this.dateService.date$)).subscribe(dates => {
        this.datemodel = dates;
        this.startTime = this.formatDate(this.datemodel.startdateTime);
        this.endTime = this.formatDate(this.datemodel.enddateTime);
        this.loadData();
      });
  }

  ngAfterViewInit(): void {
    const tooltipTriggerList = Array.from(document.querySelectorAll('[data-bs-toggle="tooltip"]'));
    tooltipTriggerList.forEach((el: any) => {
      new bootstrap.Tooltip(el);
    });
  }

  ngOnDestroy(): void {
    this.destroy$.next();
    this.destroy$.complete();
    this.datesubscription.unsubscribe();
    this.themeObserver?.disconnect();
  }

  formatDate(date: string) {
    date = date.replace(/-/g, "");
    date = date.replace(/:/g, "");
    date = date.replace(" ", "")
    return parseInt(date);
  }

  parseTimeBucket(bucket: string): Date {
    const year = +bucket.slice(0, 4);
    const month = +bucket.slice(4, 6) - 1; // 0-based index
    const day = +bucket.slice(6, 8);
    const hour = +bucket.slice(8, 10);
    const minute = +bucket.slice(10, 12);
    return new Date(year, month, day, hour, minute);
  }

  loadData(): void { 
    this.getCpuUtilization();
    this.getFreeableMemory();
    this.getRdsSwapUsage();
    this.getDatabaseConnections();

    this.getFreeStorageSpace();
    this.getDiskQueueDepth();
    this.getReadLatency();

    this.getReadIops();
    this.getWriteIops();
    this.getReadThroughput();
    this.getWriteThroughput();

    this.getNetworkReceiveThroughput();
    this.getNetworkTransmitThroughput();
  }

  getCpuUtilization(): void {
    this.rdsApiService.getCpuUtilization(this.serviceId, this.startTime, this.endTime).pipe(takeUntil(this.destroy$)).subscribe({
      next: (data: any) => {
        try {
          this.getCpuUtilizationCharts(data.metrics);
        } catch (e) {
          console.error("Error occured:", e);
        }
      },
      error: (err) => {
        console.error("API Error:", err);
      }
    });
  }

  getCpuUtilizationCharts(data: { time_bucket: string;[key: string]: any }[]): void {
    try {
      const keys = Array.from(
        new Set(
          data.flatMap(item => Object.keys(item).filter(k => k !== 'time_bucket'))
        )
      );

      const styles = getComputedStyle(document.body);
      const labelColor = styles.getPropertyValue('--text-color').trim();
      const gridColor = styles.getPropertyValue('--chart-grid-line').trim();
      const tooltipBgColor = styles.getPropertyValue('--tooltip-bg-color').trim();
      const tooltipTextColor = styles.getPropertyValue('--tooltip-text-color').trim();
      const noDataColor = styles.getPropertyValue('--noData-color').trim();

      if (keys.length === 0) {
        this.renderEmptyState('cpuUtilizationChartContainer');
        this.cpuUtilizationChart = null;
        return;
      }

      const parsedDates = data.map(item => this.parseTimeBucket(item.time_bucket));

      let format: 'date' | 'time' = 'date';
      if (parsedDates.length > 1) {
        const timeDiff = Math.abs(parsedDates[1].getTime() - parsedDates[0].getTime());
        format = timeDiff >= 24 * 60 * 60 * 1000 ? 'date' : 'time';
      }

      const categories = parsedDates.map(date =>
        format === 'date'
          ? date.toLocaleDateString()
          : date.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })
      );

      const series: Highcharts.SeriesSplineOptions[] = keys.map(key => ({
        name: key.replace(/_/g, ' ').replace(/\b\w/g, l => l.toUpperCase()),
        type: 'spline',
        marker: { radius: 2 },
        lineWidth: 1,
        data: data.map(d => {
          const y = Number(d[key]) || 0;
          return { y };
        })
      }));

      if (this.cpuUtilizationChart) {
        this.cpuUtilizationChart.destroy();
      }

      this.cpuUtilizationChart = Highcharts.chart('cpuUtilizationChartContainer', {
        chart: {
          type: 'spline',
          backgroundColor: 'transparent',
          spacing: [5, 5, 5, 5],
          style: { fontSize: '10px' }
        },
        title: { text: undefined },
        xAxis: {
          categories,
          tickPositions: [0, categories.length - 1],
          title: { text: "" },
          labels: {
            style: { color: labelColor, fontSize: '9px' },
            y: 10,
            formatter: function () {
              return categories[this.pos];
            }
          },
          gridLineColor: gridColor,
          lineColor: gridColor,
          tickColor: gridColor
        },
        yAxis: {
          min: 0,
          tickAmount: 6,
          title: { text: "" },
          labels: { style: { color: labelColor, fontSize: '9px' } },
          gridLineColor: gridColor,
        },
        tooltip: {
          shared: true,
          backgroundColor: tooltipBgColor,
          style: { color: tooltipTextColor, fontSize: '10px' },
        },
        legend: { enabled: false },
        series: series as Highcharts.SeriesOptionsType[],
        credits: { enabled: false },
        exporting: { enabled: false }
      });
      if (!this.charts.includes(this.cpuUtilizationChart)) {
        this.charts.push(this.cpuUtilizationChart);
        this.syncCharts(this.charts);
      }
    } catch (e) {
      console.error("Error Occurred ", e);
    }
  }

